"""Generated documentation: data dictionary, lineage, classification, access, quality, sample run."""

from __future__ import annotations

from datetime import date
from pathlib import Path

from . import oracle, policy, spec, types
from .spec import Lakehouse

BANNER = "<!-- Generated by medallion from spec/. Do not edit by hand. -->\n\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def data_dictionary(lh: Lakehouse) -> str:
    out = [BANNER, "# Data dictionary\n\n"]
    out.append(
        "Every table, its owner and classification, its columns and the checks applied to it. "
        "System columns (`_source_file`, `_ingested_at`, `__START_AT`, `__END_AT`) are added by the pipeline.\n"
    )
    for layer in spec.LAYERS:
        out.append(f"\n## {layer.capitalize()}\n")
        for t in lh.layer(layer):
            out.append(f"\n### `{t.fqn}`\n\n{t.comment}\n\n")
            out.append(
                f"Owner `{t.owner}` · domain `{t.domain}` · classification **{t.classification}** · "
                f"spec `spec/tables/{t.file}`\n\n"
            )
            rows = []
            for name, typ in spec.target_columns(t):
                c = t.column(name)
                if c is None:
                    rows.append([f"`{name}`", types.spark_type(typ), "", "system column"])
                    continue
                flag = f"personal data, mask `{c.mask}`" if c.pii else ""
                rows.append([f"`{name}`", types.spark_type(typ), flag, c.comment])
            out.append(_table(["Column", "Type", "Handling", "Description"], rows))
    return "".join(out)


def lineage(lh: Lakehouse) -> str:
    lines = ["flowchart LR"]
    for t in lh.layer("bronze"):
        assert t.source is not None
        lines.append(
            f'  src_{t.name}[("landing/{t.source.path}")] --> b_{t.name}["bronze.{t.name}"]'
        )
    for t in lh.layer("silver"):
        up = t.upstream or ""
        base = up.split(".")[-1]
        lines.append(f'  b_{base} --> s_{t.name}["silver.{t.name}"]')
        if any(e.action == "drop" for e in t.expectations):
            lines.append(
                f'  b_{base} -.->|"failed rules"| q_{t.name}["silver.{t.name}_quarantine"]'
            )
    for t in lh.layer("gold"):
        assert t.query is not None
        for ref in dict.fromkeys([t.query.table, *[j.table for j in t.query.joins]]):
            layer, name = ref.split(".")
            prefix = "s" if layer == "silver" else "g"
            lines.append(f'  {prefix}_{name} --> g_{t.name}["gold.{t.name}"]')
    body = "\n".join(lines)
    return (
        BANNER
        + "# Lineage\n\nSolid arrows carry data into the next table; dotted arrows send rows that fail a drop "
        "expectation to quarantine. Each silver table also has a `_validated` staging table, left out here.\n\n"
        f"```mermaid\n{body}\n```\n"
    )


def classification(lh: Lakehouse) -> str:
    out = [BANNER, "# Classification and personal data\n\n"]
    rows = [
        [f"`{t.fqn}`", t.classification, t.owner, str(sum(1 for c in t.columns if c.pii))]
        for t in sorted(lh.tables, key=lambda x: (-policy._rank(x.classification), x.fqn))
    ]
    out.append(_table(["Table", "Classification", "Owner", "Personal data columns"], rows))
    out.append("\n## Personal data columns and masks\n\n")
    pii = [
        [f"`{t.fqn}`", f"`{c.name}`", f"`{c.mask}`"] for t in lh.tables for c in t.columns if c.pii
    ]
    out.append(_table(["Table", "Column", "Mask"], pii))
    plat = lh.platform
    exempt = ", ".join(f"`{g.name}`" for g in plat.groups if g.role in ("privileged", "runner"))
    out.append(
        f"\nReaders in {exempt} see real values. Everyone else sees the mask. The runner group is "
        "exempt so the pipeline reads real values and does not copy masked ones downstream.\n"
    )
    return "".join(out)


def access(lh: Lakehouse) -> str:
    p = lh.platform
    out = [
        BANNER,
        "# Access\n\nSchema-level grants by environment. `USE CATALOG` and `USE SCHEMA` are implied.\n",
    ]
    for env in p.environments:
        out.append(f"\n## {env} (`{p.catalog(env)}`)\n\n")
        rows = []
        for g in p.grants:
            if env in g.envs:
                role = next((x.role for x in p.groups if x.name == g.group), "?")
                rows.append([f"`{g.group}`", role, f"`{g.schema}`", ", ".join(g.privileges)])
        out.append(_table(["Group", "Role", "Schema", "Privileges"], rows))
    return "".join(out)


def quality(lh: Lakehouse) -> str:
    out = [BANNER, "# Data quality expectations\n\n"]
    out.append(
        "`warn` keeps the row and counts the violation. `drop` removes the row from silver and writes it to "
        "the quarantine table with the rules it failed. `fail` stops the update, for contract breaks where "
        "continuing would corrupt downstream tables.\n"
    )
    for t in lh.layer("silver"):
        out.append(f"\n## `{t.fqn}`\n\n")
        out.append(
            _table(
                ["Expectation", "Action", "Rule"],
                [[f"`{e.name}`", e.action, f"`{e.rule}`"] for e in t.expectations],
            )
        )
    out.append(
        "\n## Bronze\n\nEvery bronze table counts rows with rescued data in `rescued_data_empty` (warn).\n"
    )
    return "".join(out)


def rules_doc() -> str:
    rows = [[f"`{i}`", sev, title, why] for i, sev, title, why in policy.catalog()]
    return (
        BANNER
        + "# Policy rules\n\n`medallion lint` runs these over the specification before anything is generated.\n\n"
        + _table(["Rule", "Severity", "Requirement", "Why"], rows)
    )


def sample_run(lh: Lakehouse, data_root: Path) -> str:
    res = oracle.run(lh, data_root)
    out = [BANNER, "# Sample run\n\n"]
    out.append(
        "The reference executor builds every table from the files in `spec/data/`. It models the pipeline; "
        "it is not Databricks. Assumptions are in [oracle-assumptions](../oracle-assumptions.md).\n\n## Row counts\n\n"
    )
    rows = []
    for t in lh.tables:
        extra = f"{len(res.tables.get(t.fqn + '_quarantine', []))}" if t.layer == "silver" else ""
        rows.append([f"`{t.fqn}`", str(len(res.tables[t.fqn])), extra])
    out.append(_table(["Table", "Rows", "Quarantined"], rows))
    out.append("\n## Expectations with violations\n\n")
    bad = [m for m in res.metrics if m.failed]
    out.append(
        _table(
            ["Table", "Expectation", "Action", "Passed", "Failed"],
            [[f"`{m.table}`", f"`{m.name}`", m.action, str(m.passed), str(m.failed)] for m in bad],
        )
    )
    out.append("\n## Quarantine reasons\n\n")
    q = []
    for t in lh.layer("silver"):
        for r in res.tables.get(f"{t.fqn}_quarantine", []):
            ident = next(iter(r[k] for k in t.cdc.keys), None) if t.cdc else None
            q.append([f"`{t.fqn}`", repr(ident), ", ".join(r["failed_rules"])])
    out.append(_table(["Table", "Key", "Failed rules"], q))
    out.append("\n## The same gold row, two readers\n\n")
    cv = res.tables["gold.customer_value"][0]
    plain = oracle.view_as(lh, "gold.customer_value", [cv], privileged=False)[0]
    priv = oracle.view_as(lh, "gold.customer_value", [cv], privileged=True)[0]
    out.append(
        _table(
            ["Reader", "customer_id", "email"],
            [
                ["privileged or pipeline", priv["customer_id"], priv["email"]],
                ["everyone else", plain["customer_id"], plain["email"]],
            ],
        )
    )
    return "".join(out)


def render(lh: Lakehouse, data_root: Path | None) -> dict[str, str]:
    out = {
        "docs/generated/data-dictionary.md": data_dictionary(lh),
        "docs/generated/lineage.md": lineage(lh),
        "docs/generated/classification.md": classification(lh),
        "docs/generated/access.md": access(lh),
        "docs/generated/quality.md": quality(lh),
        "docs/generated/policy-rules.md": rules_doc(),
    }
    if data_root is not None and data_root.exists():
        out["docs/generated/sample-run.md"] = sample_run(lh, data_root)
    return out


