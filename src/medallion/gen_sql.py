"""Render pipeline SQL (Lakeflow Spark Declarative Pipelines) from table specifications.

Every statement uses the pipeline parameter ``${catalog}`` so one set of files serves every
environment. The SQL here follows the Databricks documentation for streaming tables,
materialized views, expectations, ``AUTO CDC`` flows and column masks. It has not been run
against a workspace: see the README section on what has and has not been verified.
"""

from __future__ import annotations

from . import exprcheck, spec, types
from .spec import Column, Lakehouse, Table

HEADER = "-- Generated by medallion from spec/tables/{file}. Do not edit by hand.\n"
CATALOG = "${catalog}"
SYSTEM_COMMENTS = {
    "_source_file": "Path of the file this row was read from",
    "_source_modified_at": "Modification time of the source file",
    "_ingested_at": "When the pipeline ingested the row",
    "_rescued_data": "Fields that did not fit the schema, as JSON",
    "__START_AT": "Start of this version (inclusive)",
    "__END_AT": "End of this version (exclusive); null for the current version",
    "failed_rules": "Names of the drop expectations this row failed",
}


def lit(text: str) -> str:
    """A Spark SQL string literal."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def mask_fn(kind: str) -> str:
    return f"{CATALOG}.governance.mask_{kind}"


def _coldef(name: str, typ: str, comment: str, mask: str | None = None) -> str:
    out = f"  {name} {types.spark_type(typ)} COMMENT {lit(comment)}"
    if mask:
        out += f" MASK {mask_fn(mask)}"
    return out


def _props(t: Table, extra: dict[str, str] | None = None) -> str:
    props = {
        "governance.owner": t.owner,
        "governance.domain": t.domain,
        "governance.classification": t.classification,
        "governance.spec": f"spec/tables/{t.file}",
    }
    props.update(extra or {})
    body = ",\n".join(f"  {lit(k)} = {lit(v)}" for k, v in props.items())
    return f"TBLPROPERTIES (\n{body}\n)"


def _declared(t: Table, drop: set[str] | None = None, masks: bool = True) -> list[str]:
    drop = drop or set()
    return [
        _coldef(c.name, c.type, c.comment, c.mask if masks else None)
        for c in t.columns
        if c.name not in drop
    ]


def _system(names: list[tuple[str, str]], comment_map: dict[str, str] | None = None) -> list[str]:
    cm = comment_map or SYSTEM_COMMENTS
    return [_coldef(n, ty, cm[n]) for n, ty in names]


def _constraint(name: str, rule: str, action: str) -> str:
    tail = {"warn": "", "drop": " ON VIOLATION DROP ROW", "fail": " ON VIOLATION FAIL UPDATE"}[
        action
    ]
    return f"  CONSTRAINT {name} EXPECT ({rule}){tail}"


def bronze_sql(t: Table) -> str:
    assert t.source is not None
    schema = ", ".join(f"{c.name} STRING" for c in t.columns)
    cols = _declared(t) + _system(list(spec.BRONZE_METADATA))
    cons = [_constraint("rescued_data_empty", "_rescued_data IS NULL", "warn")]
    names = ",\n  ".join(c.name for c in t.columns)
    opts = "".join(f",\n  {k} => {lit(v)}" for k, v in sorted(t.source.options.items()))
    return (
        HEADER.format(file=t.file)
        + f"CREATE OR REFRESH STREAMING TABLE {CATALOG}.bronze.{t.name} (\n"
        + ",\n".join(cols + cons)
        + f"\n)\nCOMMENT {lit(t.comment)}\n"
        + _props(t, {"pipelines.reset.allowed": "false"})
        + f"\nAS SELECT\n  {names},\n"
        "  _metadata.file_path AS _source_file,\n"
        "  _metadata.file_modification_time AS _source_modified_at,\n"
        "  current_timestamp() AS _ingested_at,\n"
        "  _rescued_data\n"
        f"FROM STREAM read_files(\n  '/Volumes/{CATALOG}/landing/{{volume}}/{t.source.path}',\n"
        f"  format => {lit(t.source.format)},\n  schema => {lit(schema)},\n"
        f"  rescuedDataColumn => '_rescued_data'{opts}\n);\n"
    )


def _typed_select(t: Table, indent: str = "  ") -> str:
    items = []
    for c in t.columns:
        assert c.expr is not None
        items.append(f"{indent}try_cast({c.expr} AS {types.spark_type(c.type)}) AS {c.name}")
    items += [f"{indent}_source_file", f"{indent}_ingested_at"]
    return ",\n".join(items)


def _drop_rules(t: Table) -> list[spec.Expectation]:
    return [e for e in t.expectations if e.action == "drop"]


def history_excluded(t: Table) -> list[str]:
    """Columns that never open a new version of a type 2 row."""
    assert t.cdc is not None
    return sorted({t.cdc.sequence_by, "_source_file", "_ingested_at"})


def silver_sql(t: Table) -> str:
    assert t.cdc is not None and t.upstream is not None
    src = f"{CATALOG}.{t.upstream}"
    base_sys = [("_source_file", "string"), ("_ingested_at", "timestamp")]
    out = [HEADER.format(file=t.file)]

    # 1. validated: typed, with every expectation attached
    out.append("-- Typed rows with expectations applied; the input to the change flow.\n")
    # Masked as well: schema-level grants cover this table, and the runner group is exempt.
    cols = _declared(t) + _system(base_sys)
    cons = [_constraint(e.name, e.rule, e.action) for e in t.expectations]
    out.append(
        f"CREATE OR REFRESH STREAMING TABLE {CATALOG}.silver.{t.name}_validated (\n"
        + ",\n".join(cols + cons)
        + f"\n)\nCOMMENT {lit('Staging for silver.' + t.name + ': typed rows that passed validation. Not for consumers.')}\n"
        + _props(t, {"governance.role": "staging"})
        + f"\nAS SELECT\n{_typed_select(t)}\nFROM STREAM({src});\n"
    )

    # 2. the target and its change flow
    dropped = set(t.cdc.drop_columns)
    target_cols = _declared(t, drop=dropped) + _system(base_sys)
    if t.cdc.scd == 2:
        seq = t.column(t.cdc.sequence_by)
        assert seq is not None
        target_cols += [_coldef(n, seq.type, SYSTEM_COMMENTS[n]) for n in spec.SCD2_COLUMNS]
    flow = [
        f"CREATE FLOW silver_{t.name}_apply_changes AS AUTO CDC INTO {CATALOG}.silver.{t.name}",
        f"FROM STREAM({CATALOG}.silver.{t.name}_validated)",
        f"KEYS ({', '.join(t.cdc.keys)})",
    ]
    if t.cdc.delete_when:
        flow.append(f"APPLY AS DELETE WHEN {t.cdc.delete_when}")
    flow.append(f"SEQUENCE BY {t.cdc.sequence_by}")
    if dropped:
        flow.append(f"COLUMNS * EXCEPT ({', '.join(sorted(dropped))})")
    if t.cdc.scd == 2:
        # Only business columns open a new version; system columns change on every event.
        flow.append("STORED AS SCD TYPE 2")
        flow.append(f"TRACK HISTORY ON * EXCEPT ({', '.join(history_excluded(t))});")
    else:
        flow.append("STORED AS SCD TYPE 1;")
    out.append(
        f"\n-- The consumer-facing table. SCD type {t.cdc.scd}: "
        + ("one row per key." if t.cdc.scd == 1 else "one row per version of each key.")
        + "\n"
        + f"CREATE OR REFRESH STREAMING TABLE {CATALOG}.silver.{t.name} (\n"
        + ",\n".join(target_cols)
        + f"\n)\nCOMMENT {lit(t.comment)}\n"
        + _props(t, {"governance.role": "serving"})
        + ";\n\n"
        + "\n".join(flow)
        + "\n"
    )

    # 3. quarantine: rows that failed a drop or fail expectation, with the reasons
    strong = _drop_rules(t)  # a failing rule stops the update, so nothing reaches quarantine
    if strong:
        qcols = (
            _declared(t)
            + _system(base_sys)
            + [
                _coldef("failed_rules", "string", SYSTEM_COMMENTS["failed_rules"]).replace(
                    " STRING ", " ARRAY<STRING> "
                )
            ]
        )
        cases = ",\n    ".join(
            f"CASE WHEN coalesce({e.rule}, false) THEN NULL ELSE {lit(e.name)} END" for e in strong
        )
        allrules = " AND ".join(f"({e.rule})" for e in strong)
        out.append(
            f"\n-- Rows that failed a drop expectation, kept for investigation and replay.\n"
            f"CREATE OR REFRESH STREAMING TABLE {CATALOG}.silver.{t.name}_quarantine (\n"
            + ",\n".join(qcols)
            + f"\n)\nCOMMENT {lit('Rows from ' + t.upstream + ' that failed a drop expectation for silver.' + t.name + ', with the rules they failed.')}\n"
            + _props(t, {"governance.role": "quarantine"})
            + f"\nAS SELECT\n  *,\n  filter(array(\n    {cases}\n  ), x -> x IS NOT NULL) AS failed_rules\n"
            f"FROM (\n  SELECT\n{_typed_select(t, '    ')}\n  FROM STREAM({src})\n)\n"
            f"WHERE NOT coalesce({allrules}, false);\n"
        )
    return "".join(out)


def _gold_select(c: Column) -> str:
    assert c.expr is not None
    return f"  CAST({c.expr} AS {types.spark_type(c.type)}) AS {c.name}"


def gold_sql(t: Table) -> str:
    assert t.query is not None
    q = t.query
    sel = ",\n".join(_gold_select(c) for c in t.columns)
    sql = (
        HEADER.format(file=t.file)
        + f"CREATE OR REFRESH MATERIALIZED VIEW {CATALOG}.gold.{t.name} (\n"
        + ",\n".join(_declared(t))
        + f"\n)\nCOMMENT {lit(t.comment)}\n"
        + _props(t, {"governance.grain": ", ".join(c.name for c in t.columns if c.group)})
        + f"\nAS SELECT\n{sel}\nFROM {CATALOG}.{q.table} AS {q.alias}"
    )
    for j in q.joins:
        sql += f"\n{j.kind.upper()} JOIN {CATALOG}.{j.table} AS {j.alias} ON {j.on}"
    if q.where:
        sql += f"\nWHERE {q.where}"
    group = [c.expr for c in t.columns if c.group and c.expr]
    if group:
        sql += "\nGROUP BY " + ", ".join(group)
    return sql + ";\n"


def render(lh: Lakehouse) -> dict[str, str]:
    """Relative path (under the bundle) to file content for every pipeline SQL file."""
    out: dict[str, str] = {}
    volume = lh.platform.landing_volume
    for t in lh.tables:
        if t.layer == "bronze":
            out[f"src/pipelines/bronze/{t.name}.sql"] = bronze_sql(t).replace("{volume}", volume)
        elif t.layer == "silver":
            out[f"src/pipelines/silver/{t.name}.sql"] = silver_sql(t)
        else:
            out[f"src/pipelines/gold/{t.name}.sql"] = gold_sql(t)
    return out


__all__ = ["exprcheck", "render"]
