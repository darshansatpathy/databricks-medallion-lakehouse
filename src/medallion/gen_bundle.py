"""Render the Databricks Asset Bundle: root file, one pipeline and one job."""

from __future__ import annotations

from typing import Any

from . import yamlout
from .spec import Lakehouse

PLACEHOLDER_SP = "00000000-0000-0000-0000-000000000000"


def databricks_yml(lh: Lakehouse) -> str:
    p = lh.platform
    targets: dict[str, Any] = {}
    for env in p.environments:
        t: dict[str, Any] = {}
        if env == p.environments[0]:
            t["mode"] = "development"
            t["default"] = True
        else:
            t["mode"] = "production"
            t["workspace"] = {
                "root_path": "/Workspace/Shared/.bundle/${bundle.name}/${bundle.target}"
            }
            t["run_as"] = {"service_principal_name": "${var.run_as_service_principal}"}
        variables: dict[str, Any] = {"catalog": p.catalog(env)}
        if env == p.environments[-1]:
            variables["schedule_status"] = "UNPAUSED"
        t["variables"] = variables
        targets[env] = t
    root: dict[str, Any] = {
        "bundle": {"name": p.name},
        "include": ["resources/*.yml"],
        "variables": {
            "catalog": {"description": "Unity Catalog catalog for this target (set per target)"},
            "warehouse_id": {
                "description": "SQL warehouse that runs the governance task; pass with --var or BUNDLE_VAR_warehouse_id"
            },
            "run_as_service_principal": {
                "description": "Application ID of the service principal that runs staging and prod. Replace the placeholder.",
                "default": PLACEHOLDER_SP,
            },
            "schedule_status": {
                "description": "PAUSED or UNPAUSED; only prod is unpaused by default",
                "default": "PAUSED",
            },
        },
        "targets": targets,
    }
    header = (
        "# Generated by medallion from spec/. Do not edit by hand.\n"
        "# Validate with: databricks bundle validate -t dev --var warehouse_id=<id>\n"
    )
    return header + yamlout.dump(root)


def pipeline_yml(lh: Lakehouse) -> str:
    root = {
        "resources": {
            "pipelines": {
                lh.platform.name.replace("-", "_"): {
                    "name": "[${bundle.target}] " + lh.platform.name,
                    "catalog": "${var.catalog}",
                    "schema": "bronze",
                    "serverless": True,
                    "continuous": False,
                    "root_path": "../src/pipelines",
                    "libraries": [{"glob": {"include": "../src/pipelines/**"}}],
                    "configuration": {
                        "catalog": "${var.catalog}",
                        "spark.sql.session.timeZone": "UTC",
                    },
                }
            }
        }
    }
    return "# Generated by medallion from spec/. Do not edit by hand.\n" + yamlout.dump(root)


def job_yml(lh: Lakehouse) -> str:
    key = lh.platform.name.replace("-", "_")
    root = {
        "resources": {
            "jobs": {
                f"{key}_daily": {
                    "name": "[${bundle.target}] " + lh.platform.name + " daily",
                    "max_concurrent_runs": 1,
                    "timeout_seconds": 14400,
                    "schedule": {
                        "quartz_cron_expression": "0 30 2 * * ?",
                        "timezone_id": "UTC",
                        "pause_status": "${var.schedule_status}",
                    },
                    "tasks": [
                        {
                            "task_key": "apply_governance",
                            "sql_task": {
                                "warehouse_id": "${var.warehouse_id}",
                                "file": {"path": "../src/governance/${bundle.target}.sql"},
                            },
                        },
                        {
                            "task_key": "refresh_pipeline",
                            "depends_on": [{"task_key": "apply_governance"}],
                            "pipeline_task": {"pipeline_id": f"${{resources.pipelines.{key}.id}}"},
                        },
                    ],
                }
            }
        }
    }
    return "# Generated by medallion from spec/. Do not edit by hand.\n" + yamlout.dump(root)


def render(lh: Lakehouse) -> dict[str, str]:
    key = lh.platform.name.replace("-", "_")
    return {
        "databricks.yml": databricks_yml(lh),
        f"resources/{key}.pipeline.yml": pipeline_yml(lh),
        f"resources/{key}.job.yml": job_yml(lh),
    }
