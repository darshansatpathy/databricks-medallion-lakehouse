"""Render Unity Catalog governance SQL (catalog, schemas, volume, mask functions, grants).

One file per environment with the catalog name resolved, because the statements run in a SQL
task before the pipeline, outside pipeline parameter substitution.
"""

from __future__ import annotations

from .gen_sql import lit
from .spec import Lakehouse

SCHEMA_COMMENTS = {
    "landing": "Landing zone: source files as delivered",
    "bronze": "Raw, append-only copies of source data as text",
    "silver": "Typed, validated, deduplicated current state",
    "gold": "Curated aggregates for consumption",
    "governance": "Mask functions and other governance objects",
}


def mask_function_sql(catalog: str, kind: str, exempt: list[str]) -> str:
    check = " OR ".join(f"is_account_group_member({lit(g)})" for g in exempt)
    body = {
        "email": "concat('***@', substring_index(v, '@', -1))",
        "redact": "'[REDACTED]'",
        "last4": "concat(repeat('*', greatest(length(v) - 4, 0)), right(v, 4))",
        "hash": "sha2(v, 256)",
    }[kind]
    return (
        f"CREATE OR REPLACE FUNCTION {catalog}.governance.mask_{kind}(v STRING)\n"
        f"RETURNS STRING\n"
        f"COMMENT {lit('Column mask (' + kind + '): readers in the privileged and runner groups see the real value')}\n"
        f"RETURN CASE\n  WHEN v IS NULL THEN NULL\n  WHEN {check} THEN v\n  ELSE {body}\nEND;\n"
    )


def render_env(lh: Lakehouse, env: str) -> str:
    p = lh.platform
    cat = p.catalog(env)
    exempt = [g.name for g in p.groups if g.role in ("privileged", "runner")]
    kinds = sorted({c.mask for t in lh.tables for c in t.columns if c.mask})
    out = [
        f"-- Generated by medallion from spec/platform.toml. Do not edit by hand.\n"
        f"-- Environment: {env}. Run before the pipeline; every statement is idempotent.\n\n",
        f"CREATE CATALOG IF NOT EXISTS {cat} COMMENT {lit(p.description)};\n",
    ]
    for s, comment in SCHEMA_COMMENTS.items():
        out.append(f"CREATE SCHEMA IF NOT EXISTS {cat}.{s} COMMENT {lit(comment)};\n")
    out.append(
        f"CREATE VOLUME IF NOT EXISTS {cat}.landing.{p.landing_volume} "
        f"COMMENT {lit('Landing files by source: one folder per source table')};\n\n"
    )
    out.append("-- Column masks. Bind them in the pipeline SQL; they must exist first.\n")
    out.extend(mask_function_sql(cat, k, exempt) + "\n" for k in kinds)
    out.append("-- Access\n")
    by_group: dict[str, list[tuple[str, tuple[str, ...]]]] = {}
    for g in p.grants:
        if env in g.envs:
            by_group.setdefault(g.group, []).append((g.schema, g.privileges))
    for group in sorted(by_group):
        out.append(f"GRANT USE CATALOG ON CATALOG {cat} TO `{group}`;\n")
        for schema, privs in by_group[group]:
            plist = ", ".join(privs if "ALL PRIVILEGES" in privs else ["USE SCHEMA", *privs])
            out.append(f"GRANT {plist} ON SCHEMA {cat}.{schema} TO `{group}`;\n")
    admins = p.group_by_role("admin")
    if admins:
        out.append(f"\nALTER CATALOG {cat} OWNER TO `{admins[0].name}`;\n")
    return "".join(out)


def render(lh: Lakehouse) -> dict[str, str]:
    return {f"src/governance/{e}.sql": render_env(lh, e) for e in lh.platform.environments}
