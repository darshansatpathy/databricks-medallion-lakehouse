from __future__ import annotations

import re

import pytest

from medallion import gen_sql, spec


@pytest.fixture(scope="module")
def files(lakehouse):
    return gen_sql.render(lakehouse)


def test_one_file_per_table(lakehouse, files):
    assert sorted(files) == sorted(
        f"src/pipelines/{t.layer}/{t.name}.sql" for t in lakehouse.tables
    )


def test_every_file_has_the_generated_header_and_balanced_parentheses(files):
    for path, sql in files.items():
        assert sql.startswith("-- Generated by medallion from spec/tables/"), path
        stripped = re.sub(r"'(?:[^'\\]|\\.)*'", "''", sql)
        assert stripped.count("(") == stripped.count(")"), path
        assert "{volume}" not in sql and "None" not in sql, path


def test_every_statement_ends_with_a_semicolon(files):
    for path, sql in files.items():
        body = "\n".join(line for line in sql.splitlines() if not line.startswith("--")).strip()
        assert body.endswith(";"), path


def test_all_table_references_use_the_catalog_parameter(files):
    pattern = re.compile(r"\b(?:FROM|JOIN)\s+(STREAM read_files|STREAM\(\S+?\)|\(|\S+)")
    for path, sql in files.items():
        refs = pattern.findall(sql)
        assert refs, path
        for ref in refs:
            if ref in ("STREAM read_files", "("):
                continue
            inner = ref.removeprefix("STREAM(").removesuffix(")")
            assert inner.startswith("${catalog}."), f"{path}: {ref}"
        for target in re.findall(r"(?:TABLE|VIEW|INTO)\s+(\$\{catalog\}\.\w+\.\w+)", sql):
            assert target.count(".") == 2


def test_bronze_reads_files_into_text_with_rescue_and_metadata(files):
    sql = files["src/pipelines/bronze/orders.sql"]
    assert "CREATE OR REFRESH STREAMING TABLE ${catalog}.bronze.orders" in sql
    assert "FROM STREAM read_files(" in sql and "'/Volumes/${catalog}/landing/raw/orders'" in sql
    assert "format => 'json'" in sql and "rescuedDataColumn => '_rescued_data'" in sql
    assert "schema => 'order_id STRING, customer_id STRING" in sql
    assert (
        "_metadata.file_path AS _source_file" in sql
        and "current_timestamp() AS _ingested_at" in sql
    )
    assert "CONSTRAINT rescued_data_empty EXPECT (_rescued_data IS NULL)\n)" in sql
    assert "'pipelines.reset.allowed' = 'false'" in sql
    assert "ON VIOLATION" not in sql  # bronze never drops or fails


