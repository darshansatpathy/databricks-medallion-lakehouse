def test_silver_expectations_use_the_right_violation_clause(lakehouse, files):
    sql = files["src/pipelines/silver/orders.sql"]
    for e in lakehouse.table("silver.orders").expectations:  # type: ignore[union-attr]
        tail = {"warn": "", "drop": " ON VIOLATION DROP ROW", "fail": " ON VIOLATION FAIL UPDATE"}[
            e.action
        ]
        assert f"CONSTRAINT {e.name} EXPECT ({e.rule}){tail}" in sql, e.name


def test_silver_change_flow_for_type_1(files):
    sql = files["src/pipelines/silver/orders.sql"]
    flow = sql[sql.index("CREATE FLOW") : sql.index("-- Rows that failed")].strip()
    assert flow == (
        "CREATE FLOW silver_orders_apply_changes AS AUTO CDC INTO ${catalog}.silver.orders\n"
        "FROM STREAM(${catalog}.silver.orders_validated)\n"
        "KEYS (order_id)\n"
        "APPLY AS DELETE WHEN op = 'D'\n"
        "SEQUENCE BY updated_at\n"
        "COLUMNS * EXCEPT (op)\n"
        "STORED AS SCD TYPE 1;"
    )
    target = sql[sql.index("${catalog}.silver.orders (\n") : sql.index("CREATE FLOW")]
    assert "  op STRING" not in target


