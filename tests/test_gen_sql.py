def test_quarantine_captures_failed_drop_rules_only(lakehouse, files):
    sql = files["src/pipelines/silver/orders.sql"]
    q = sql[sql.index("silver.orders_quarantine") :]
    assert "failed_rules ARRAY<STRING>" in q
    for e in lakehouse.table("silver.orders").expectations:  # type: ignore[union-attr]
        assert (f"THEN NULL ELSE '{e.name}' END" in q) == (e.action == "drop"), e.name
    assert "WHERE NOT coalesce((order_id IS NOT NULL AND length(order_id) > 0) AND" in q


def test_gold_is_a_materialized_view_with_cast_select_join_filter_and_group(files):
    sql = files["src/pipelines/gold/daily_revenue.sql"]
    assert "CREATE OR REFRESH MATERIALIZED VIEW ${catalog}.gold.daily_revenue (" in sql
    assert "CAST(sum(o.amount) AS DECIMAL(18,2)) AS revenue" in sql
    assert (
        "FROM ${catalog}.silver.orders AS o\nLEFT JOIN ${catalog}.silver.customers AS c ON o.customer_id = c.customer_id AND c.__END_AT IS NULL"
        in sql
    )
    assert "WHERE o.status = 'completed'" in sql
    assert sql.rstrip().endswith("GROUP BY to_date(o.order_ts), coalesce(c.country, 'ZZ');")
    assert "'governance.grain' = 'order_date, country'" in sql


