def test_literals_are_escaped_for_spark():
    assert gen_sql.lit("it's") == r"'it\'s'"
    assert gen_sql.lit("a\\b") == "'a\\\\b'"
    assert gen_sql.lit("plain") == "'plain'"


def test_generated_columns_match_the_spec_columns(lakehouse, files):
    for t in lakehouse.layer("gold"):
        sql = files[f"src/pipelines/gold/{t.name}.sql"]
        for c in t.columns:
            assert f"  {c.name} {spec_type(c.type)} COMMENT" in sql
            assert f"AS {c.name}" in sql


def spec_type(t: str) -> str:
    from medallion import types

    return types.spark_type(t)


def test_comment_with_a_quote_survives(lakehouse):
    import dataclasses

    t = lakehouse.table("gold.daily_revenue")
    assert t is not None
    tricky = dataclasses.replace(t, comment='Finance\'s "daily" view of revenue for the board pack')
    sql = gen_sql.gold_sql(tricky)
    assert "COMMENT 'Finance\\'s \"daily\" view of revenue for the board pack'" in sql


def test_source_options_are_rendered_sorted(lakehouse):
    import dataclasses

    t = lakehouse.table("bronze.orders")
    assert t is not None and t.source is not None
    with_opts = dataclasses.replace(t, source=spec.Source("json", "orders", {"b": "2", "a": "1"}))
    sql = gen_sql.bronze_sql(with_opts)
    assert sql.index("a => '1'") < sql.index("b => '2'")
